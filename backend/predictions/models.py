"""
Database models for storing stock price direction predictions.
"""

from django.db import models
from stocks.models import Stock


class Prediction(models.Model):
    """
    Persisted prediction record generated by the ML PredictionService.

    Idempotency is guaranteed by the unique constraint on
    (stock, market_data_timestamp, model_version).
    """

    stock = models.ForeignKey(
        Stock,
        on_delete=models.CASCADE,
        related_name="predictions",
    )

    symbol = models.CharField(
        max_length=20,
        db_index=True,
    )

    prediction = models.CharField(
        max_length=10,
        help_text="Direction label: UP or DOWN",
    )

    direction = models.IntegerField(
        help_text="Binary direction: 1 for UP, 0 for DOWN",
    )

    probability = models.FloatField(
        help_text="Model confidence probability for the predicted class",
    )

    probabilities = models.JSONField(
        default=dict,
        help_text="Class probabilities dictionary, e.g. {'DOWN': 0.28, 'UP': 0.72}",
    )

    model_type = models.CharField(
        max_length=50,
        default="xgboost_classifier",
    )

    model_version = models.CharField(
        max_length=20,
        default="v1",
    )

    market_data_timestamp = models.DateTimeField(
        null=True,
        blank=True,
        db_index=True,
        help_text="Timestamp of the underlying market price bar used for feature generation",
    )

    features_used = models.JSONField(
        default=list,
        blank=True,
        help_text="List of feature column names evaluated by the model",
    )

    feature_snapshot = models.JSONField(
        default=dict,
        blank=True,
        null=True,
        help_text="Snapshot of the 12 feature values at prediction time",
    )

    actual_direction = models.CharField(
        max_length=10,
        blank=True,
        null=True,
        help_text="Realized market direction: UP or DOWN",
    )

    actual_return = models.FloatField(
        blank=True,
        null=True,
        help_text="Realized next-day percentage return",
    )

    outcome = models.CharField(
        max_length=20,
        default="PENDING",
        db_index=True,
        help_text="Outcome status: CORRECT, INCORRECT, PENDING",
    )

    resolved_at = models.DateTimeField(
        blank=True,
        null=True,
        help_text="Timestamp when the prediction outcome was resolved",
    )

    latency_ms = models.FloatField(
        blank=True,
        null=True,
        help_text="Inference latency in milliseconds",
    )

    generated_at = models.DateTimeField(
        auto_now_add=True,
        db_index=True,
        help_text="Timestamp when the prediction was generated and persisted",
    )

    class Meta:
        db_table = "predictions"
        ordering = ["-generated_at"]

        constraints = [
            models.UniqueConstraint(
                fields=["stock", "market_data_timestamp", "model_version"],
                name="unique_prediction_per_market_timestamp",
            )
        ]

        indexes = [
            models.Index(fields=["stock", "-generated_at"]),
            models.Index(fields=["symbol", "-generated_at"]),
            models.Index(fields=["market_data_timestamp"]),
            models.Index(fields=["symbol", "outcome"]),
            models.Index(fields=["model_version", "outcome"]),
        ]

    def __str__(self):
        return f"{self.symbol} - {self.prediction} ({self.probability:.2f}) [{self.outcome}] at {self.generated_at}"


class ModelVersion(models.Model):
    """
    Registry record for a machine learning model version.

    Tracks model lifecycle state (candidate -> staging -> production -> retired / failed),
    feature schema version, hyperparameter configuration, and validation/test metrics.
    """

    STATUS_CHOICES = [
        ("candidate", "Candidate"),
        ("staging", "Staging"),
        ("production", "Production"),
        ("retired", "Retired"),
        ("failed", "Failed"),
    ]

    symbol = models.CharField(
        max_length=20,
        db_index=True,
        help_text="Stock ticker symbol (e.g. TCS.NS)",
    )

    model_type = models.CharField(
        max_length=50,
        default="xgboost_classifier",
        db_index=True,
        help_text="Model architecture identifier (e.g. xgboost_classifier)",
    )

    version = models.CharField(
        max_length=20,
        help_text="Semantic or sequential model version tag (e.g. v1, v2)",
    )

    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default="candidate",
        db_index=True,
        help_text="Lifecycle status of this model version",
    )

    artifact_path = models.CharField(
        max_length=255,
        help_text="Relative or absolute path to the serialized model artifact (.joblib)",
    )

    metadata_path = models.CharField(
        max_length=255,
        help_text="Relative or absolute path to the model metadata file (.json)",
    )

    feature_schema_version = models.CharField(
        max_length=20,
        default="v1",
        help_text="Feature schema version expected by this model version",
    )

    features = models.JSONField(
        default=list,
        help_text="Ordered list of feature column names used for training and inference",
    )

    hyperparameters = models.JSONField(
        default=dict,
        blank=True,
        help_text="Model hyperparameters dictionary",
    )

    metrics = models.JSONField(
        default=dict,
        blank=True,
        help_text="Evaluation metrics dictionary (e.g. accuracy, f1, roc_auc, log_loss)",
    )

    created_at = models.DateTimeField(
        auto_now_add=True,
        db_index=True,
        help_text="Timestamp when the model version was registered",
    )

    promoted_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="Timestamp when the model was promoted to production",
    )

    retired_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="Timestamp when the model was retired from production",
    )

    class Meta:
        db_table = "model_versions"
        ordering = ["symbol", "model_type", "-created_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["symbol", "model_type", "version"],
                name="unique_model_version_per_symbol_and_type",
            )
        ]
        indexes = [
            models.Index(fields=["symbol", "model_type", "status"]),
            models.Index(fields=["symbol", "status"]),
        ]

    def __str__(self):
        return f"{self.symbol} - {self.model_type} ({self.version}) [{self.status}]"


class ModelEvaluation(models.Model):
    """
    Granular evaluation record for a specific model version and dataset split.
    """

    SPLIT_CHOICES = [
        ("train", "Train"),
        ("validation", "Validation"),
        ("test", "Test"),
    ]

    model_version = models.ForeignKey(
        ModelVersion,
        on_delete=models.CASCADE,
        related_name="evaluations",
        help_text="Model version evaluated",
    )

    dataset_split = models.CharField(
        max_length=20,
        choices=SPLIT_CHOICES,
        help_text="Dataset split on which metric was evaluated (train, validation, test)",
    )

    metric_name = models.CharField(
        max_length=50,
        help_text="Metric name (e.g. accuracy, precision, recall, f1, roc_auc, log_loss)",
    )

    metric_value = models.FloatField(
        help_text="Calculated metric value",
    )

    evaluated_at = models.DateTimeField(
        auto_now_add=True,
        help_text="Timestamp when the evaluation was computed",
    )

    class Meta:
        db_table = "model_evaluations"
        ordering = ["model_version", "dataset_split", "metric_name"]
        indexes = [
            models.Index(fields=["model_version", "dataset_split", "metric_name"]),
        ]

    def __str__(self):
        return f"{self.model_version.version} - {self.dataset_split}:{self.metric_name}={self.metric_value:.4f}"

