"""
Prediction tool for AI Agent.
Retrieves actual directional predictions and confidence scores generated by the XGBoost pipeline.
"""
import logging
from typing import Any, Dict
from ml.inference.exceptions import ModelNotFoundError
from ml.inference.prediction_service import PredictionService
from predictions.models import Prediction
from stocks.universe import get_stock_metadata

logger = logging.getLogger(__name__)


def get_prediction(symbol: str) -> Dict[str, Any]:
    """
    Retrieve the current directional prediction, probabilities, and model version for a stock.
    """
    normalized = symbol.strip().upper()
    meta = get_stock_metadata(normalized) or {}

    # Check for latest persisted prediction in database first
    latest_pred = (
        Prediction.objects.filter(symbol=normalized)
        .order_by("-market_data_timestamp", "-generated_at")
        .first()
    )

    if latest_pred:
        prob = float(latest_pred.probability)
        probs = latest_pred.probabilities or {}
        up_prob = round(float(probs.get("UP", prob)) * 100, 1)
        down_prob = round(float(probs.get("DOWN", 1.0 - prob)) * 100, 1)

        return {
            "status": "ok",
            "trained": True,
            "symbol": normalized,
            "company_name": meta.get("company_name", normalized),
            "prediction": latest_pred.prediction,
            "direction": latest_pred.direction,
            "confidence_percent": round(prob * 100, 1),
            "probabilities": {
                "UP_percent": up_prob,
                "DOWN_percent": down_prob,
            },
            "model_type": "xgboost_classifier",
            "model_version": latest_pred.model_version or "v1",
            "timestamp": latest_pred.market_data_timestamp.strftime("%Y-%m-%d %H:%M:%S UTC") if latest_pred.market_data_timestamp else "Latest session",
            "outcome": latest_pred.outcome,
            "features_used": latest_pred.features_used or [],
        }

    # If not in DB, attempt live inference via PredictionService
    try:
        service = PredictionService()
        result = service.predict(symbol=normalized)
        prob = float(result.probability)
        up_prob = round(float(result.probabilities.get("UP", prob)) * 100, 1)
        down_prob = round(float(result.probabilities.get("DOWN", 1.0 - prob)) * 100, 1)

        return {
            "status": "ok",
            "trained": True,
            "symbol": normalized,
            "company_name": meta.get("company_name", normalized),
            "prediction": result.prediction,
            "direction": result.direction,
            "confidence_percent": round(prob * 100, 1),
            "probabilities": {
                "UP_percent": up_prob,
                "DOWN_percent": down_prob,
            },
            "model_type": result.model_type,
            "model_version": result.model_version,
            "timestamp": result.timestamp.strftime("%Y-%m-%d %H:%M:%S UTC") if hasattr(result.timestamp, "strftime") else str(result.timestamp),
            "features_used": result.features_used or [],
        }
    except ModelNotFoundError:
        return {
            "status": "model_not_found",
            "trained": False,
            "symbol": normalized,
            "company_name": meta.get("company_name", normalized),
            "message": (
                f"There is currently no trained machine learning model artifact available for {normalized}. "
                "The 4 stocks with pre-trained models are TCS.NS, INFY.NS, RELIANCE.NS, and HDFCBANK.NS. "
                f"A model for {normalized} can be trained anytime via 'python manage.py train_model --symbol {normalized} --promote'."
            ),
        }
    except Exception as exc:
        logger.warning("Error fetching prediction for %s: %s", normalized, exc)
        return {
            "status": "error",
            "trained": False,
            "symbol": normalized,
            "message": f"Could not retrieve prediction for {normalized}: {str(exc)}",
        }
